function getTranslation(path, lang) {
    return path.split(".").reduce((value, key) => value && value[key], translations[lang]);
}

function setLanguage(lang) {
    const nextLang = translations[lang] ? lang : "tr";

    document.documentElement.lang = nextLang;
    localStorage.setItem("siteLanguage", nextLang);

    document.querySelectorAll("[data-i18n]").forEach((el) => {
        const value = getTranslation(el.dataset.i18n, nextLang);
        if (value) {
            el.textContent = value;
        }
    });

    document.querySelectorAll("[data-lang-button]").forEach((button) => {
        const isActive = button.dataset.langButton === nextLang;
        button.classList.toggle("active", isActive);
        button.setAttribute("aria-pressed", String(isActive));
    });
}

