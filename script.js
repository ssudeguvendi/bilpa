function scrollToVisibleSection(element) {
    const navbar = document.querySelector(".navbar");
    const offset = navbar ? navbar.offsetHeight + 18 : 80;
    const top = element.getBoundingClientRect().top + window.pageYOffset - offset;

    window.scrollTo({
        top: Math.max(0, top),
        behavior: "smooth"
    });
}

